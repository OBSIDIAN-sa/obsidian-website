#!/usr/bin/env python3
"""Builds assets/js/staff.en.js — the English edition of the staff page — from assets/js/staff.js.

Every Arabic string in the script is looked up in tools/staff-en.json and swapped for its English text, so the two
editions always share one code base. Run it after any change to staff.js:

    python3 tools/make-staff-en.py            # writes staff.en.js, lists strings that still have no translation
    python3 tools/make-staff-en.py --missing  # only prints the untranslated strings as JSON, to fill in

Strings that must stay Arabic whatever the language (project types stored with the request, WhatsApp texts sent to
customers) are listed under "keep" in the JSON file.
"""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'assets/js/staff.js').read_text(encoding='utf-8')
data = json.loads((root / 'tools/staff-en.json').read_text(encoding='utf-8'))
table, keep = data['strings'], set(data.get('keep', []))
AR = re.compile(r'[؀-ۿ]')
LIT = re.compile(r"'((?:[^'\\\n]|\\.)*)'")
missing = []

def swap(m):
    text = m.group(1)
    if not AR.search(text) or text in keep:
        return m.group(0)
    if text in table:
        return "'" + table[text].replace("\\", "\\\\").replace("'", "\\'") + "'"
    if text not in missing:
        missing.append(text)
    return m.group(0)

out = []
for line in src.split('\n'):
    code = line
    # leave comments and regular-expression literals alone: only quoted strings are swapped
    if line.lstrip().startswith('//'):
        out.append(line); continue
    out.append(LIT.sub(swap, code))
en = '\n'.join(out)
en = en.replace("'ar-SA-u-ca-gregory-nu-latn'", "'en-GB'")
# the language switch points the other way in this edition
for old, new in [("h('button', cls, 'EN')", "h('button', cls, 'عربي')"), ("b.setAttribute('aria-label', 'English')", "b.setAttribute('aria-label', 'العربية')"), ("localStorage.setItem('obs_lang', 'en')", "localStorage.setItem('obs_lang', 'ar')")]:
    assert old in en, old
    en = en.replace(old, new)
en = en.replace("/* OBSIDIAN DESIGN — staff dashboard.", "/* GENERATED by tools/make-staff-en.py from staff.js — do not edit by hand.\n   OBSIDIAN DESIGN — staff dashboard (English edition).", 1)

if '--missing' in sys.argv:
    print(json.dumps({k: '' for k in missing}, ensure_ascii=False, indent=0))
else:
    (root / 'assets/js/staff.en.js').write_text(en, encoding='utf-8')
    print('staff.en.js written;', len(missing), 'strings without a translation')
    for m in missing: print('  ', m)
